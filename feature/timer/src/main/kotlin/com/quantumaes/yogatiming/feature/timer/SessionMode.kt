package com.quantumaes.yogatiming.feature.timer

/**
 * Что показывает рабочий экран (docs/03-GESTURES.md §3).
 *
 * Режим живёт в состоянии экрана, а не в модели: занятие идёт одинаково и в
 * фокусе, и под блокировкой, а от поворота экрана режим сохраняется
 * `rememberSaveable`.
 *
 * Блокировки среди значений нет намеренно (замечание 5 полевой проверки
 * 2026-08-05). Карта жестов описывает три режима, но блокировка — не третий
 * вид экрана, а слой поверх любого из двух: она забирает касания, не трогая
 * того, что под ней. Пока запирали только с обычного экрана, разница не
 * проявлялась; со значком замка в фокусе она стала видна сразу — запирая
 * гигантские цифры, пользователь получал бы под пеленой обычный экран с
 * кнопками, а после разблокировки оставался бы на нём. Поэтому блокировка —
 * отдельный флаг рядом с этим режимом (`locked` в `TimerScreen`).
 */
enum class SessionMode {
    /** Кнопки видны, свайпы выключены — иначе они спорили бы с нажатиями. */
    NORMAL,

    /** Цифры во весь экран и два значка в углу. Кнопок нет, поэтому свайп однозначен. */
    FOCUS,
    ;

    val isFocus: Boolean get() = this == FOCUS
}
