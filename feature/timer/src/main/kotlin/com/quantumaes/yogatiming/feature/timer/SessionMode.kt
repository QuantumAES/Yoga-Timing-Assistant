package com.quantumaes.yogatiming.feature.timer

/**
 * Режим рабочего экрана (docs/03-GESTURES.md §3).
 *
 * Каждый жест определён во всех трёх режимах — пустых клеток в карте нет.
 * Режим живёт в состоянии экрана, а не в модели: занятие идёт одинаково и в
 * фокусе, и под блокировкой, а от поворота экрана режим сохраняется
 * `rememberSaveable`.
 */
enum class SessionMode {
    /** Кнопки видны, свайпы выключены — иначе они спорили бы с нажатиями. */
    NORMAL,

    /** Только цифры. Кнопок нет, поэтому свайп однозначен. */
    FOCUS,

    /** Касания игнорируются, кроме удержания секунду. */
    LOCK,
    ;

    val isLocked: Boolean get() = this == LOCK

    val isFocus: Boolean get() = this == FOCUS
}
