package com.quantumaes.yogatiming.domain.hint

/**
 * Разовая подсказка: показывается один раз, дальше живёт в настройках.
 *
 * Прямое следствие политики `docs/05-PLAY-DECLARATIONS.md` §5: «без запугивания
 * и без повторных показов». Подсказка описывает состояние системы, которое
 * приложение изменить не может, поэтому повторный показ ничего не улучшает —
 * он только приучает не читать сообщения.
 */
enum class Hint(
    val key: String,
) {
    /** Приложение не в списке исключений энергосбережения. */
    BATTERY_OPTIMIZATION("battery_optimization"),

    /** Точные алармы запрещены пользователем (API 31–32). */
    EXACT_ALARMS("exact_alarms"),
}

/**
 * Что из разовых подсказок пользователь уже видел и закрыл.
 *
 * Контракт объявлен в домене, реализация — в `:core:datastore`: экранам не
 * положено знать, где именно лежит флаг.
 */
interface HintStore {
    suspend fun isDismissed(hint: Hint): Boolean

    suspend fun dismiss(hint: Hint)

    /** «Показывать подсказки снова» из настроек (Фаза 7). */
    suspend fun reset()
}
