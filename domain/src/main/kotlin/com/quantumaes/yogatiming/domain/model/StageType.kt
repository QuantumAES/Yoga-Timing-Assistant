package com.quantumaes.yogatiming.domain.model

/**
 * Тип этапа занятия (ТЗ, Экран 3).
 *
 * Влияет на поведение движка и на оповещения по умолчанию:
 * - [REST] при выборе в редакторе предлагает пресет «Тихий» (решение C-6);
 * - [FREE] не имеет плановой длительности — счёт идёт вверх до ручного перехода,
 *   WARNING/END-оповещения к нему не привязываются (решение B-5).
 */
enum class StageType {
    /** Обычный этап с фиксированной длительностью. */
    NORMAL,

    /** Короткий переход между блоками. */
    TRANSITION,

    /** Отдых, шавасана, релаксация — резкие сигналы недопустимы. */
    REST,

    /** Свободный этап: длительность не задана, завершается вручную. */
    FREE,
}
