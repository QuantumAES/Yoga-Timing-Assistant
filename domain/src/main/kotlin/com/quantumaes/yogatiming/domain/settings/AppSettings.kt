package com.quantumaes.yogatiming.domain.settings

import com.quantumaes.yogatiming.timer.engine.model.PauseMode

/**
 * Оформление приложения (Экран 6 настроек).
 *
 * Приоритет применения (docs/06-MVP-SCOPE.md, решение C-4):
 * явный выбор пользователя → системная тема.
 *
 * [SYSTEM] стоит первым в перечислении и служит значением по умолчанию:
 * пользователь, настроивший тему один раз в системе, вправе не настраивать её
 * заново в каждом приложении.
 */
enum class ThemeMode {
    /** Следовать системной теме. */
    SYSTEM,

    LIGHT,

    DARK,
    ;

    companion object {
        val DEFAULT = SYSTEM

        /** Неизвестное значение из хранилища не роняет запуск — деградируем к [DEFAULT]. */
        fun fromName(raw: String?): ThemeMode = entries.firstOrNull { it.name == raw } ?: DEFAULT
    }
}

/**
 * Форма индикатора отсчёта на рабочем экране (Экран 4).
 *
 * Кольцо — исходная форма (ТЗ, Экран 4): круг заполняется от вертикали и
 * читается как «сколько осталось» одним взглядом, не требуя сравнивать длину
 * закрашенного с длиной пустого. Но круг — квадрат, и на невысоком экране его
 * диаметр упирается в остаток высоты, а не в ширину: шапка, полоса «что дальше»
 * и кнопки забирают своё, и кольцу достаётся, скажем, 250 dp там, где по ширине
 * было бы 350. Цифры внутри круга живут в его хорде — то есть ещё меньше.
 *
 * [PANEL] снимает именно это ограничение: прямоугольник со скруглёнными углами
 * занимает всю ширину и всю оставшуюся высоту, цифрам достаётся почти вся
 * ширина экрана, и на телефоне 5" они выходят в полтора раза крупнее. Прогресс
 * при этом рисуется тем же способом — обводкой по периметру от середины
 * верхней стороны по часовой стрелке.
 *
 * Выбор оставлен пользователю, а не выведен из размера экрана: «мелко» — это
 * про зрение и про то, с какого расстояния смотрят, а не про диагональ. На
 * планшете, лежащем в трёх метрах, прямоугольник тоже уместнее.
 */
enum class TimerShape {
    /** Кольцо. Форма из ТЗ и значение по умолчанию. */
    RING,

    /** Прямоугольник со скруглёнными углами: крупнее цифры на небольших экранах. */
    PANEL,
    ;

    companion object {
        val DEFAULT = RING

        /** Неизвестное значение из хранилища не роняет запуск — деградируем к [DEFAULT]. */
        fun fromName(raw: String?): TimerShape = entries.firstOrNull { it.name == raw } ?: DEFAULT
    }
}

/**
 * Пользовательские настройки приложения (Экран 6, Фаза 7).
 *
 * Класс единый намеренно — экран настроек читает одно состояние, а не десяток
 * независимых потоков, которые обновляются вразнобой. Значения по умолчанию
 * описывают приложение сразу после установки: занятие должно быть проводимым
 * без единого захода в настройки.
 *
 * @param dynamicColor палитра Material You из обоев. На рабочий экран занятия
 *   не распространяется никогда (docs/06-MVP-SCOPE.md §4).
 * @param voiceEnabled разрешён ли канал VOICE. **Выключен по умолчанию**:
 *   синтезатор читает санскритские названия асан с чужими ударениями, и
 *   занятие, начатое сразу после установки, не должно этим огорошивать.
 *   Пресеты при этом не переписываются — канал остаётся в конфигах и оживает
 *   одним переключателем, когда произношение этапов настроено
 *   (`Stage.voiceName`).
 * @param alertVolumePercent общий множитель громкости поверх той, что задана
 *   в оповещении (переформулировка P0-6: системную громкость приложение не
 *   трогает никогда, только собственный программный гейн). 100 — «как
 *   настроено в профиле», и это значение по умолчанию: настройка, которая
 *   сразу после установки что-то приглушает, обманывает редактор оповещений.
 * @param duckMusicOnAlert приглушать ли фоновую музыку на время сигнала
 *   (ТЗ §5.3). Выключенный ducking означает «не просить audio focus вовсе»:
 *   сигнал прозвучит поверх музыки, ничего не приглушая. Это осознанный выбор
 *   тех, кто ведёт занятие под свой плейлист и не хочет провалов в нём.
 * @param speechRatePercent скорость речи TTS, проценты от нормальной.
 * @param keepScreenOn держать ли экран включённым на рабочем экране занятия.
 *   По умолчанию да: инструктор смотрит на цифры с коврика и не может
 *   дотянуться до телефона, чтобы разбудить экран. Отсчёт от настройки не
 *   зависит — его держит partial WakeLock сервиса.
 * @param autoDimEnabled гасить ли яркость в режиме фокуса после 15 секунд
 *   бездействия (ТЗ, Экран 4).
 * @param timerShape форма индикатора отсчёта: кольцо или прямоугольник
 *   (см. [TimerShape]). Настройка про читаемость, а не про вкус: на невысоком
 *   экране прямоугольник даёт цифрам в полтора раза больший кегль.
 * @param settingsFromSession пускать ли в настройки прямо с рабочего экрана.
 *   По умолчанию да: громкость и скорость речи чаще всего хочется поправить
 *   именно тогда, когда сигнал уже прозвучал не так, — то есть посреди
 *   занятия. Выключается теми, кто отдаёт телефон в чужие руки: занятие идёт
 *   дальше в любом случае, но лишней двери на экране не остаётся.
 * @param pauseMode с какого режима начинается пауза (см. [PauseMode]). Оба
 *   режима доступны и на самом занятии — одним нажатием по плашке паузы;
 *   настройка задаёт лишь тот, с которого пауза начинается. Тот, кто ведёт
 *   индивидуальные занятия по предоплате, чаще ставит на паузу этап — время
 *   идёт в любом случае; тот, у кого зал свободен, — всё занятие.
 * @param onboardingCompleted показан ли онбординг. Отдельный флаг, а не
 *   «первый запуск»: онбординг можно пересмотреть из настроек.
 */
data class AppSettings(
    val themeMode: ThemeMode = ThemeMode.DEFAULT,
    val dynamicColor: Boolean = false,
    val voiceEnabled: Boolean = false,
    val alertVolumePercent: Int = DEFAULT_ALERT_VOLUME,
    val duckMusicOnAlert: Boolean = true,
    val speechRatePercent: Int = DEFAULT_SPEECH_RATE,
    val keepScreenOn: Boolean = true,
    val autoDimEnabled: Boolean = true,
    val timerShape: TimerShape = TimerShape.DEFAULT,
    val settingsFromSession: Boolean = true,
    val pauseMode: PauseMode = PauseMode.DEFAULT,
    val onboardingCompleted: Boolean = false,
) {
    /** Множитель громкости в долях единицы — в том виде, в каком его ждёт звуковой тракт. */
    val alertVolumeFactor: Float
        get() = alertVolumePercent.coerceIn(MIN_ALERT_VOLUME, MAX_ALERT_VOLUME) / PERCENT

    /** Скорость речи в долях единицы: 1.0 — нормальная для выбранного движка. */
    val speechRate: Float
        get() = speechRatePercent.coerceIn(MIN_SPEECH_RATE, MAX_SPEECH_RATE) / PERCENT

    companion object {
        const val DEFAULT_ALERT_VOLUME = 100
        const val MIN_ALERT_VOLUME = 10
        const val MAX_ALERT_VOLUME = 100
        const val ALERT_VOLUME_STEP = 10

        const val DEFAULT_SPEECH_RATE = 100
        const val MIN_SPEECH_RATE = 50
        const val MAX_SPEECH_RATE = 200
        const val SPEECH_RATE_STEP = 10

        private const val PERCENT = 100f
    }
}
