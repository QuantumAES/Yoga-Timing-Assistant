package com.quantumaes.yogatiming.core.audio

/**
 * Комбинирующий акут U+0301 — общепринятая пометка ударения для синтезаторов
 * речи. Ставится **после** ударной гласной и на письме сливается с ней.
 */
private const val STRESS_MARK = '́'

/** Как ударение вводит пользователь: плюс перед ударной гласной — «шав+асана». */
private const val STRESS_INPUT = '+'

/**
 * Гласные обоих алфавитов: русские названия асан, английские названия этапов.
 * Согласной ударение не ставят, поэтому плюс перед ней — обычный плюс.
 */
private const val VOWELS = "аеёиоуыэюяАЕЁИОУЫЭЮЯaeiouyAEIOUY"

/**
 * Ударения в произносимом тексте.
 *
 * Санскритские названия асан синтезатор читает с ударением по своим правилам:
 * «шавáсана» превращается в «шавасáну», «вирабхадрáсана» — во что придётся.
 * Средство исправить это ровно одно — пометить ударный слог в самом тексте;
 * фонемной разметки (SSML `phoneme`) Android TTS не принимает.
 *
 * Вводится ударение плюсом перед гласной — так его набирают с любой клавиатуры,
 * в отличие от комбинирующего акута. Уже проставленный акут проходит насквозь:
 * текст, скопированный из словаря, работает как есть.
 *
 * Поддержка ударения — свойство конкретного движка TTS, а не гарантия. Если
 * движок пометку игнорирует, произношение остаётся прежним, но текст от неё
 * не ломается: лишний символ движки отбрасывают.
 */
object Pronunciation {
    /**
     * @return текст, в котором «+гласная» заменена на «гласная + U+0301».
     *   Плюс перед согласной, цифрой или в конце строки остаётся плюсом.
     */
    fun withStressMarks(text: String): String {
        if (STRESS_INPUT !in text) return text

        val result = StringBuilder(text.length)
        var index = 0
        while (index < text.length) {
            val char = text[index]
            val next = text.getOrNull(index + 1)
            if (char == STRESS_INPUT && next != null && next in VOWELS) {
                result.append(next).append(STRESS_MARK)
                index += 2
            } else {
                result.append(char)
                index++
            }
        }
        return result.toString()
    }
}
