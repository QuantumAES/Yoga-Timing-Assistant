package com.quantumaes.yogatiming.timer.engine.model

/**
 * Что именно останавливает пауза.
 *
 * Различие не техническое, а продуктовое. Инструктор нажимает «Пауза» по двум
 * несовместимым поводам:
 *
 * - **занятие прервано** — звонок в дверь, опоздавший, надо выйти. Практики
 *   сейчас нет ни у кого, и время, проведённое в этом состоянии, к занятию
 *   не относится;
 * - **занятие идёт, но этап стоит** — разбор позы, вопрос из зала, показ на
 *   себе. Практика продолжается, зал занят, аренда тикает: остановился ровно
 *   один этап, а не занятие.
 *
 * До появления бюджета занятия (`SessionBudget`) разницы не существовало —
 * останавливать было нечего, кроме этапа. Как только у занятия появился конец,
 * заданный часами, а не суммой этапов, второй режим стал обязательным: иначе
 * пятиминутный разбор позы бесследно съедал бы пять минут бюджета.
 */
enum class PauseMode {
    /** Стоит всё, включая часы занятия. */
    SESSION,

    /**
     * Стоит только этап; часы занятия идут дальше.
     *
     * Время, проведённое в этом режиме, копится в [SessionState.holdMs] и
     * вычитается из бюджета — на экране оно и есть «дополнительное время».
     */
    STAGE,
    ;

    companion object {
        val DEFAULT = SESSION
    }
}
