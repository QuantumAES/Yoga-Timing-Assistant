package com.quantumaes.yogatiming.timer.engine.model

/**
 * Сколько времени у занятия есть на самом деле.
 *
 * Плановая длительность профиля отвечает на вопрос «сколько занятие займёт»,
 * бюджет — на вопрос «сколько его готовы терпеть»: аренда зала до 20:00,
 * индивидуальное занятие оплачено на час, следующая группа приходит в 19:30.
 * Это разные числа, и до появления бюджета второе нигде не хранилось — из-за
 * чего остаток занятия на экране пересчитывался при каждом переходе между
 * этапами и никогда не отвечал на вопрос «когда я закончу».
 *
 * Бюджет считается **по часам занятия**, а не по сумме этапов: ручной переход,
 * правка ±30 с и пауза этапа его не двигают. Именно поэтому «осталось» с
 * бюджетом монотонно убывает, а без бюджета — прыгает вслед за планом.
 *
 * @param targetMs целевая длительность занятия от старта до конца.
 * @param toleranceMs допустимый перерасход. Ноль — «ровно столько и ни минутой
 *   больше» (индивидуальное занятие по предоплате); десять минут — «арендодатель
 *   не возражает» (групповое занятие с эластичным окном). Величина влияет только
 *   на то, с какого момента перерасход показывается как нарушение, а не как
 *   запас, — сам отсчёт от неё не зависит.
 * @param wrapUpOffsetMs за сколько до [targetMs] прозвучит отсечка. Ноль —
 *   отсечка выключена.
 * @param wrapUpAlert чем отсечка сигналит; `null` — молча, только на экране.
 */
data class SessionBudget(
    val targetMs: Long,
    val toleranceMs: Long = 0L,
    val wrapUpOffsetMs: Long = 0L,
    val wrapUpAlert: PlannedAlert? = null,
) {
    /** Предел, после которого перерасход перестаёт быть допустимым. */
    val limitMs: Long get() = targetMs + toleranceMs

    /** Момент отсечки в терминах «сколько занятие уже идёт». */
    val wrapUpAtMs: Long? get() = (targetMs - wrapUpOffsetMs).takeIf { wrapUpOffsetMs > 0L && it > 0L }
}
