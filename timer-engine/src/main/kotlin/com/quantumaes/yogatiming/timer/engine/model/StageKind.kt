package com.quantumaes.yogatiming.timer.engine.model

/**
 * Тип этапа с точки зрения движка.
 *
 * Дублирует `StageType` из `:domain` намеренно. Правило зависимостей
 * (docs/02-TIMER-CORE-DESIGN.md §1) направлено сверху вниз: `:domain` знает про
 * движок, движок про `:domain` — нет. Перечисление из четырёх значений — вся
 * цена этого правила; преобразование выполняется там же, где уже разрешается
 * наследование оповещений, — при сборке плана в `:domain`.
 *
 * Поведение движка различает только [FREE] и всё остальное: у свободного этапа
 * нет конца, значит нет ни дедлайнов, ни остатка (решение B-5). Остальные
 * значения движок переносит в снапшот нетронутыми — они нужны интерфейсу.
 */
enum class StageKind {
    NORMAL,
    TRANSITION,
    REST,

    /** Длительность не задана: счёт идёт вверх до ручного перехода. */
    FREE,
    ;

    /** Есть ли у этапа плановый конец — а с ним остаток, дедлайны и оповещения. */
    val hasDeadline: Boolean get() = this != FREE
}
